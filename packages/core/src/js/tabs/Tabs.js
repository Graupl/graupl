/**
 * @file
 * The Tabs class.
 */

import TabToggle from "./TabToggle.js";
import {
  isValidType,
  isValidClassList,
} from "@accessible-ecosystem/core/validate.js";
import {
  keyPress,
  preventEvent,
} from "@accessible-ecosystem/core/eventHelpers.js";
import Component from "@accessible-ecosystem/core/Component.js";

/**
 * The Tabs component.
 *
 * @extends Component
 *
 * Protected fields are documented below.
 *
 * @property {Object<string, HTMLElement|HTMLElement[]>} _dom                         - The DOM elements within the tabs.
 * @property {HTMLElement}                               _dom.tabs                    - The tabs element.
 * @property {HTMLElement}                               _dom.tabList                 - The tab list element.
 * @property {HTMLElement[]}                             _dom.tabToggles              - An array of tab toggles.
 * @property {HTMLElement[]}                             _dom.tabContents             - An array of tab contents.
 * @property {string}                                    _rootDOMElement              - The root DOM element of the tabs.
 * @property {string[]}                                  _protectedDOMElements        - The DOM elements within the tabs that cannot be reset or generated by the tabs themselves.
 * @property {Object<string, string>}                    _selectors                   - The query selectors used by the tabs.
 * @property {string}                                    _selectors.tabList           - The query selector for the tab list.
 * @property {string}                                    _selectors.tabToggles        - The query selector for tab toggles.
 * @property {string}                                    _selectors.tabContents       - The query selector for tab contents.
 * @property {Object<string, TabToggle[]>}               _elements                    - The instantiated elements within the tabs.
 * @property {TabToggle[]}                               _elements.tabToggles         - The list of tab toggles.
 * @property {Object<string, string|string[]>}           _classes                     - The CSS classes to apply when the tabs are in various states.
 * @property {string|string[]}                           _classes.expand              - The class(es) to apply when the tab is expanded.
 * @property {string|string[]}                           _classes.collapse            - The class(es) to apply when the tab is collapsed.
 * @property {string|string[]}                           _classes.transition          - The class(es) to apply when the tab is transitioning between states.
 * @property {string|string[]}                           _classes.initialize          - The class(es) to apply when the tab is initializing.
 * @property {Object<string, number>}                    _durations                   - The duration times (in milliseconds) for various aspects throughout the tabs.
 * @property {number}                                    _durations.transition        - The duration time (in milliseconds) for the transition between expanded and collapsed states.
 * @property {number}                                    _durations.expand            - The duration time (in milliseconds) for the transition from collapsed to expanded states.
 * @property {number}                                    _durations.collapse          - The duration time (in milliseconds) for the transition from expanded to collapsed states.
 * @property {boolean}                                   _automatic                   - A flag to set if focusing a tab toggle will automatically activate it.
 * @property {number}                                    _currentChild                - The index of the current child node.
 * @property {string}                                    _storageKey                  - The key used for storage.
 * @property {boolean}                                   _shouldStore                 - A flag to check if the component should be stored in the StorageManager.
 * @property {Object<string, CustomEvent>}               _events                      - Custom events that can be triggered throughout the tabs.
 * @property {Object<string, number>}                    _delays                      - The delay times (in milliseconds) for various aspects throughout the tabs.
 * @property {string}                                    _focusState                  - The current state of the tabs' focus.
 * @property {string}                                    _currentEvent                - The last type of event triggered within the tabs.
 * @property {string}                                    _breakpoint                  - The breakpoint that the tabs will call media query list events.
 * @property {string}                                    _mediaQueryString            - The media query to use to trigger media query list events.
 * @property {MediaQueryList|null}                       _mediaQueryList              - The MediaQueryList for the tabs.
 * @property {Function}                                  _mediaQueryListEventCallback - The callback for media query list events.
 * @property {Object<string, number>}                    _intervals                   - Intervals throughout the tabs.
 * @property {Object<string, number>}                    _timeouts                    - Timeouts throughout the tabs.
 * @property {object[]}                                  _listeners                   - Event listeners throughout the tabs.
 * @property {string}                                    _prefix                      - The prefix used for CSS custom properties and attributes.
 * @property {string}                                    _key                         - The key used to generate IDs throughout the tabs.
 * @property {string}                                    _id                          - The main ID of the tabs.
 * @property {boolean}                                   _valid                       - The validity state of the tabs.
 * @property {boolean}                                   _initialized                 - The initialized state of the tabs.
 * @property {Error[]}                                   _errors                      - The errors found throughout the tabs.
 */
class Tabs extends Component {
  _scope = "Graupl";
  _rootDOMElement = "tabs";
  _automatic = false;
  _currentChild = 0;
  _storageKey = "tabs";
  _name = "Tab";

  /**
   * Constructs a new `Tab`.
   *
   * @param {object}             options                                      - The options for generating the tab.
   * @param {HTMLElement}        [options.tabsElement]                        - The tab element in the DOM.
   * @param {string}             [options.tabListSelector = .tab-list]        - The query selector string for the tab list.
   * @param {string}             [options.tabTogglesSelector = .tab-toggle]   - The query selector string for tab toggle.
   * @param {string}             [options.tabContentsSelector = .tab-content] - The query selector string for tab content.
   * @param {?(string|string[])} [options.expandClass = show]                 - The class to apply when a tab is "expanded".
   * @param {?(string|string[])} [options.collapseClass = hide]               - The class to apply when a tab is "collapsed".
   * @param {?(string|string[])} [options.transitionClass = null]             - The class to apply when a tab is transitioning between "expanded" and "collapsed" states.
   * @param {number}             [options.transitionDuration = 300]           - The duration of the transition between "expanded" and "collapsed" states (in milliseconds).
   * @param {number}             [options.expandDuration = -1]                - The duration of the transition from "collapsed" to "expanded" states (in milliseconds).
   * @param {number}             [options.collapseDuration = -1]              - The duration of the transition from "expanded" to "collapsed" states (in milliseconds).
   * @param {boolean}            [options.automaticActivation = false]        - A flag to set if focusing a tab item toggle will automatically activate it.
   * @param {?string}            [options.prefix = graupl-]                   - The prefix to use for CSS custom properties.
   * @param {?string}            [options.key = null]                         - The key used to generate IDs throughout the tab.
   * @param {?(string|string[])} [options.initializeClass = initializing]     - The class to apply when tabs are initializing.
   * @param {boolean}            [options.initialize = false]                 - A flag to initialize the tab immediately upon creation.
   * @param {?(string|string[])} [options.openClass]                          - Deprecated. Use expandClass; this option takes precedence when supplied.
   * @param {?(string|string[])} [options.closeClass]                         - Deprecated. Use collapseClass; this option takes precedence when supplied.
   * @param {number}             [options.openDuration]                       - Deprecated. Use expandDuration; this option takes precedence when supplied.
   * @param {number}             [options.closeDuration]                      - Deprecated. Use collapseDuration; this option takes precedence when supplied.
   */
  constructor({
    tabsElement,
    tabListSelector = ".tab-list",
    tabTogglesSelector = ".tab-toggle",
    tabContentsSelector = ".tab-content",
    expandClass = "show",
    collapseClass = "hide",
    transitionClass = null,
    transitionDuration = 300,
    expandDuration = -1,
    collapseDuration = -1,
    automaticActivation = false,
    prefix = "graupl-",
    key = null,
    initializeClass = "initializing",
    openClass,
    closeClass,
    openDuration,
    closeDuration,
    initialize = false,
  }) {
    // Map deprecated options before passing the configuration to Core.
    if (openClass !== undefined) {
      console.warn(
        'Graupl Tabs option "openClass" is deprecated and will be removed. Use expandClass instead.'
      );
      expandClass = openClass;
    }

    if (closeClass !== undefined) {
      console.warn(
        'Graupl Tabs option "closeClass" is deprecated and will be removed. Use collapseClass instead.'
      );
      collapseClass = closeClass;
    }

    if (openDuration !== undefined) {
      console.warn(
        'Graupl Tabs option "openDuration" is deprecated and will be removed. Use expandDuration instead.'
      );
      expandDuration = openDuration;
    }

    if (closeDuration !== undefined) {
      console.warn(
        'Graupl Tabs option "closeDuration" is deprecated and will be removed. Use collapseDuration instead.'
      );
      collapseDuration = closeDuration;
    }

    super({
      bootstrap: false,
      initialize: false,
      prefix,
      key,
      initializeClass,
    });

    // Set DOM elements.
    this._dom.tabs = tabsElement;
    this._dom.tabList = null;
    this._dom.tabToggles = [];
    this._dom.tabContents = [];

    // Set DOM selectors.
    this._selectors.tabList = tabListSelector;
    this._selectors.tabToggles = tabTogglesSelector;
    this._selectors.tabContents = tabContentsSelector;

    // Set elements.
    this._elements.tabToggles = [];

    // Set expanded/close classes.
    this._classes.expand = expandClass || "";
    this._classes.collapse = collapseClass || "";
    this._classes.transition = transitionClass || "";

    // Set transition duration.
    this._durations.transition = transitionDuration;
    this._durations.expand = expandDuration;
    this._durations.collapse = collapseDuration;

    // Set automatic activation.
    this._automatic = automaticActivation;

    // Set up custom initialization.
    this._bootstrap();

    if (initialize) {
      this.initialize();
    }
  }

  /**
   * Registers the tabs' internal initialization and validation listeners.
   *
   * @protected
   */
  _registerEvents() {
    super._registerEvents();

    this._addInternalEventListener(this.getEventName("initialize"), (event) => {
      if (event.detail.component !== this) return;

      // Make sure the first tab is expanded if no other tab is active.
      if (
        this.elements.tabToggles.filter((toggle) => toggle.isExpanded)
          .length === 0
      ) {
        this.elements.tabToggles[0].expand();
      }
    });

    // Set up custom validation.
    this._addInternalEventListener(this.getEventName("validate"), (event) => {
      if (event.detail.component !== this) return;

      // Boolean checks.
      const booleans = {
        automaticActivation: this._automatic,
      };

      // Check the booleans.
      const booleanChecks = isValidType("boolean", booleans, {
        shouldThrow: false,
      });

      // Handle boolean check failure.
      if (!booleanChecks.status) {
        this._errors = [...this._errors, ...booleanChecks.errors];
        this._valid = false;
      }
    });
  }

  /**
   * The deprecated alias for expandClass.
   *
   * @deprecated Use expandClass instead. This property will be removed.
   *
   * @type {string|string[]}
   */
  get openClass() {
    console.warn(
      "Graupl Tabs.openClass is deprecated and will be removed. Use expandClass instead."
    );

    return this.expandClass;
  }

  set openClass(value) {
    console.warn(
      "Graupl Tabs.openClass is deprecated and will be removed. Use expandClass instead."
    );

    this.expandClass = value;
  }

  /**
   * The deprecated alias for collapseClass.
   *
   * @deprecated Use collapseClass instead. This property will be removed.
   *
   * @type {string|string[]}
   */
  get closeClass() {
    console.warn(
      "Graupl Tabs.closeClass is deprecated and will be removed. Use collapseClass instead."
    );

    return this.collapseClass;
  }

  set closeClass(value) {
    console.warn(
      "Graupl Tabs.closeClass is deprecated and will be removed. Use collapseClass instead."
    );

    this.collapseClass = value;
  }

  /**
   * The deprecated alias for expandDuration.
   *
   * @deprecated Use expandDuration instead. This property will be removed.
   *
   * @type {number}
   */
  get openDuration() {
    console.warn(
      "Graupl Tabs.openDuration is deprecated and will be removed. Use expandDuration instead."
    );

    return this.expandDuration;
  }

  set openDuration(value) {
    console.warn(
      "Graupl Tabs.openDuration is deprecated and will be removed. Use expandDuration instead."
    );

    this.expandDuration = value;
  }

  /**
   * The deprecated alias for collapseDuration.
   *
   * @deprecated Use collapseDuration instead. This property will be removed.
   *
   * @type {number}
   */
  get closeDuration() {
    console.warn(
      "Graupl Tabs.closeDuration is deprecated and will be removed. Use collapseDuration instead."
    );

    return this.collapseDuration;
  }

  set closeDuration(value) {
    console.warn(
      "Graupl Tabs.closeDuration is deprecated and will be removed. Use collapseDuration instead."
    );

    this.collapseDuration = value;
  }

  /**
   * The class(es) to apply when the tab is expanded.
   *
   * @type {string|string[]}
   *
   * @see _classes.expand
   */
  get expandClass() {
    return this._classes.expand;
  }

  set expandClass(value) {
    isValidClassList({ expandClass: value });

    if (this._classes.expand !== value) {
      this._classes.expand = value;
    }
  }

  /**
   * The class(es) to apply when the tab is collapsed.
   *
   * @type {string|string[]}
   *
   * @see _classes.collapse
   */
  get collapseClass() {
    return this._classes.collapse;
  }

  set collapseClass(value) {
    isValidClassList({ collapseClass: value });

    if (this._classes.collapse !== value) {
      this._classes.collapse = value;
    }
  }

  /**
   * The class(es) to apply when the tab is transitioning between expanded and collapsed.
   *
   * @type {string|string[]}
   *
   * @see _classes.transition
   */
  get transitionClass() {
    return this._classes.transition;
  }

  set transitionClass(value) {
    isValidClassList({ transitionClass: value });

    if (this._classes.transition !== value) {
      this._classes.transition = value;
    }
  }

  /**
   * The duration time (in milliseconds) for the transition between expanded and collapsed states.
   *
   * @type {number}
   *
   * @see _durations.transition
   */
  get transitionDuration() {
    return this._durations.transition;
  }

  set transitionDuration(value) {
    isValidType("number", { transitionDuration: value });

    if (this._durations.transition !== value) {
      this._durations.transition = value;
      this._setCustomProps();
    }
  }

  /**
   * The duration time (in milliseconds) for the transition from collapsed to expanded states.
   *
   * If expandDuration is set to -1, the transitionDuration will be used instead.
   *
   * @type {number}
   *
   * @see _durations.expand
   */
  get expandDuration() {
    return this._durations.expand === -1
      ? this.transitionDuration
      : this._durations.expand;
  }

  set expandDuration(value) {
    isValidType("number", { expandDuration: value });

    if (this._durations.expand !== value) {
      this._durations.expand = value;
      this._setCustomProps();
    }
  }

  /**
   * The duration time (in milliseconds) for the transition from expanded to collapsed states.
   *
   * If collapseDuration is set to -1, the transitionDuration will be used instead.
   *
   * @type {number}
   *
   * @see _durations.collapse
   */
  get collapseDuration() {
    return this._durations.collapse === -1
      ? this.transitionDuration
      : this._durations.collapse;
  }

  set collapseDuration(value) {
    isValidType("number", { collapseDuration: value });

    if (this._durations.collapse !== value) {
      this._durations.collapse = value;
      this._setCustomProps();
    }
  }

  /**
   * A flag to set if focusing a tab item toggle will automatically activate it.
   *
   * @type {boolean}
   *
   * @see _automatic
   */
  get isAutomatic() {
    return this._automatic;
  }

  set isAutomatic(value) {
    isValidType("boolean", { isAutomatic: value });

    if (this._automatic !== value) {
      this._automatic = value;
    }
  }

  /**
   * The current index of the tab item.
   *
   * @readonly
   *
   * @type {number}
   *
   * @see _currentChild
   */
  get currentChild() {
    return this._currentChild;
  }

  set currentChild(value) {
    isValidType("number", { currentChild: value });

    if (
      this._currentChild !== value &&
      value >= 0 &&
      value < this.elements.tabToggles.length
    ) {
      this._currentChild = value;
    }
  }

  /**
   * The currently selected tab item.
   *
   * @readonly
   *
   * @type {TabToggle}
   */
  get currentTabToggle() {
    return this.elements.tabToggles[this.currentChild];
  }

  /**
   * Sets the IDs throughout the tabs.
   *
   * The generated IDs use the key and follow the format:
   *  - tabs: `tabs-${key}`
   *  - tab-list: `tab-list-${key}`
   *
   * @protected
   */
  _setIds() {
    this.dom.tabs.id = this.dom.tabs.id || `tabs-${this.key}`;
    this.dom.tabList.id = this.dom.tabList.id || `tab-list-${this.key}`;

    this._id = this.dom.tabs.id;
  }

  /**
   * Sets ARIA attributes throughout the tabs.
   *
   * @protected
   */
  _setAriaAttributes() {
    this.dom.tabList.setAttribute("role", "tablist");
  }

  /**
   * Sets custom props throughout the tabs.
   *
   * The custom properties are:
   *   - `--graupl-tabs-transition-duration`,
   *   - `--graupl-tabs-open-transition-duration`, and
   *   - `--graupl-tabs-close-transition-duration`.
   *
   * The prefix of `graupl-` can be changed by setting the tab's prefix value.
   *
   * @protected
   */
  _setCustomProps() {
    this.dom.tabs.style.setProperty(
      `--${this.prefix}tabs-transition-duration`,
      `${this.transitionDuration}ms`
    );

    this.dom.tabs.style.setProperty(
      `--${this.prefix}tabs-open-transition-duration`,
      `${this.expandDuration}ms`
    );

    this.dom.tabs.style.setProperty(
      `--${this.prefix}tabs-close-transition-duration`,
      `${this.collapseDuration}ms`
    );
  }

  /**
   * Sets all DOM elements within the tabs.
   *
   * Utilizes _setDOMElementType.
   *
   * @protected
   */
  _setDOMElements() {
    this._setDOMElementType("tabList", { context: this.dom.tabs });

    if (this.dom.tabList) {
      this._setDOMElementType("tabToggles", { context: this.dom.tabList });
    }

    this._setDOMElementType("tabContents", { context: this.dom.tabs });
  }

  /**
   * Creates and initializes all tab toggles.
   *
   * @protected
   */
  _createChildElements() {
    this.dom.tabToggles.forEach((tabToggles, index) => {
      const toggle = new TabToggle({
        toggleElement: tabToggles,
        contentElement: this.dom.tabContents[index],
        parentTab: this,
      });

      toggle._addInternalEventListener(toggle.getEventName("preexpand"), () => {
        // Collapse all sibling tab toggles.
        toggle.collapseSiblings({
          force: true,
          emit: this.isInitialized,
          transition: this.isInitialized,
        });

        // Set the focus state of the parent tabs element.
        this.focusState = "self";
      });
      toggle._addInternalEventListener(
        toggle.getEventName("precollapse"),
        () => {
          // Set the focus state of the parent tabs element.
          this.focusState = "none";
        }
      );

      this._elements.tabToggles.push(toggle);
      toggle.initialize();
    });
  }

  /**
   * Handles focus events throughout the tab for proper use.
   *
   * - Adds a `focus` listener to every tab item so when it gains focus,
   *   it will set the tab's current child to the index of the item.
   *
   * @protected
   */
  _handleFocus() {
    this.elements.tabToggles.forEach((toggle, index) => {
      this._addEventListener("focus", toggle.dom.toggle, () => {
        this.currentChild = index;

        if (this.isAutomatic) {
          this.currentTabToggle.expand();
        }
      });
    });
  }

  /**
   * Handles click events throughout the tab item for proper use.
   *
   * - Adds a `click` listener to the tab item toggles that will toggle each tab item.
   *
   * @protected
   */
  _handleClick() {
    this.elements.tabToggles.forEach((toggle, index) => {
      this._addEventListener("click", toggle.dom.toggle, () => {
        this.currentChild = index;
        this.currentEvent = "mouse";
        toggle.expand();
      });
    });
  }

  /**
   * Handles keydown events throughout the tab item for proper use.
   *
   * This method exists to assist the _handleKeyup method.
   *
   * - Adds a `keydown` listener to all tab item toggles.
   *   - Blocks propagation on "Space", "Enter", "ArrowRight", "ArrowLeft", "Home", and "End" keys.
   */
  _handleKeydown() {
    this.dom.tabToggles.forEach((tabToggles) => {
      this._addEventListener("keydown", tabToggles, (event) => {
        this.currentEvent = "keyboard";

        const key = keyPress(event);
        const ToggleKeys = [
          "Space",
          "Enter",
          "ArrowRight",
          "ArrowLeft",
          "Home",
          "End",
        ];

        // Prevent default behavior for space and enter keys.
        if (ToggleKeys.includes(key)) {
          preventEvent(event);
        }
      });
    });
  }

  /**
   * Handles keyup events throughout the tab item for proper use.
   *
   * Adds the follow keybindings (explanations are taken from the WAI ARIA Practices Guide Tab Pattern):
   *
   * - `Enter` or `Space`:
   *   - When focus is on the tab link for a collapsed panel, expands the associated panel. If the implementation allows only one panel to be expanded, and if another panel is expanded, collapses that panel.
   *   - When focus is on the tab link for an expanded panel, collapses the panel if the implementation supports collapsing. Some implementations require one panel to be expanded at all times and allow only one panel to be expanded; so, they do not support a collapse function.
   * - `Tab`: Moves focus to the next focusable element; all focusable elements in the tab are included in the page `Tab` sequence.
   * - `Shift + Tab`: Moves focus to the previous focusable element; all focusable elements in the tab are included in the page `Tab` sequence.
   * - `Down Arrow` (Optional): If focus is on an tab link, moves focus to the next tab link. If focus is on the last tab link, either does nothing or moves focus to the first tab link.
   * - `Up Arrow` (Optional): If focus is on an tab link, moves focus to the previous tab link. If focus is on the first tab link, either does nothing or moves focus to the last tab link.
   * - `Home` (Optional): When focus is on an tab link, moves focus to the first tab link.
   * - `End` (Optional): When focus is on an tab link, moves focus to the last tab link.
   *
   * Note: When the above explanations mention "tab link", they are referring to the tab item toggle.
   */
  _handleKeyup() {
    this.dom.tabToggles.forEach((tabToggles) => {
      this._addEventListener("keyup", tabToggles, (event) => {
        this.currentEvent = "keyboard";

        const key = keyPress(event);

        switch (key) {
          case "Space":
          case "Enter":
            preventEvent(event);
            this.currentTabToggle.expand();

            break;
          case "Home":
            preventEvent(event);
            this.focusFirstChild();

            break;
          case "End":
            preventEvent(event);
            this.focusLastChild();

            break;
          case "ArrowRight":
            preventEvent(event);
            this.focusNextChild();

            break;
          case "ArrowLeft":
            preventEvent(event);
            this.focusPreviousChild();

            break;
        }
      });
    });
  }

  /**
   * Focus the tab's current child.
   */
  focusCurrentChild() {
    if (this.currentChild !== -1) {
      this.currentTabToggle.focus();
    }
  }

  /**
   * Focuses the tab's child at a given index.
   *
   * @param {number} index - The index of the child to focus.
   */
  focusChild(index) {
    this.blurCurrentChild();
    this.currentChild = index;
    this.focusCurrentChild();
  }

  /**
   * Focuses the tab's first child.
   */
  focusFirstChild() {
    this.focusChild(0);
  }

  /**
   * Focus the tab's last child.
   */
  focusLastChild() {
    this.focusChild(this.elements.tabToggles.length - 1);
  }

  /**
   * Focus the tab's next child.
   */
  focusNextChild() {
    if (this.currentChild < this.elements.tabToggles.length - 1) {
      this.focusChild(this.currentChild + 1);
    } else {
      this.focusFirstChild();
    }
  }

  /**
   * Focus the tab's previous child.
   */
  focusPreviousChild() {
    if (this.currentChild > 0) {
      this.focusChild(this.currentChild - 1);
    } else {
      this.focusLastChild();
    }
  }

  /**
   * Blurs the tab's current child.
   */
  blurCurrentChild() {
    if (this.currentChild !== -1) {
      this.currentTabToggle.blur();
    }
  }

  /**
   * Disposes child components before releasing this component's tracked work.
   */
  dispose() {
    this.elements.tabToggles.forEach((item) => item.dispose());
    super.dispose();
  }
}

export default Tabs;
