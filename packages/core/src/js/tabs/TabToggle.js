/**
 * @file
 * The TabToggle class.
 */

/* global Tabs, TransactionalValue */

import CollapsibleComponent from "@accessible-ecosystem/core/CollapsibleComponent.js";

/**
 * @event grauplTabToggleExpand
 * Fired when the tab toggle is expanded.
 *
 * @type {CustomEvent}
 *
 * @property {boolean}                   bubbles          - Whether the event bubbles.
 * @property {Object<string, TabToggle>} detail           - The event details.
 * @property {TabToggle}                 detail.component - The tab toggle that was expanded.
 */

/**
 * @event grauplTabToggleCollapse
 * Fired when the tab toggle is collapsed.
 *
 * @type {CustomEvent}
 *
 * @property {boolean}                   bubbles          - Whether the event bubbles.
 * @property {Object<string, TabToggle>} detail           - The event details.
 * @property {TabToggle}                 detail.component - The tab toggle that was collapsed.
 */

/**
 * The Tab toggle component.
 *
 * @extends CollapsibleComponent
 *
 * Protected fields are documented below.
 *
 * @property {Object<string, HTMLElement>}     _dom                         - The DOM elements within the tab toggle.
 * @property {HTMLElement}                     _dom.toggle                  - The toggle element.
 * @property {HTMLElement}                     _dom.content                 - The content element.
 * @property {string}                          _rootDOMElement              - The root DOM element of the tab toggle.
 * @property {string[]}                        _protectedDOMElements        - The DOM elements within the tab toggle that cannot be reset or generated by the tab toggle itself.
 * @property {Object<string, Tabs>}            _elements                    - The instantiated elements within the tab toggle.
 * @property {Tabs}                            _elements.parent             - The parent tabs element.
 * @property {TransactionalValue<boolean>}     _expanded                    - The active state of the tab toggle.
 * @property {Object<string, CustomEvent>}     _events                      - Custom events that can be triggered throughout the tab toggle.
 * @property {grauplTabToggleExpand}           _events.expand               - The event triggered when the tab toggle is expanded.
 * @property {grauplTabToggleCollapse}         _events.collapse             - The event triggered when the tab toggle is collapsed.
 * @property {Object<string, string>}          _selectors                   - The query selectors used by the tab toggle.
 * @property {Object<string, string|string[]>} _classes                     - The CSS classes to apply when the tab toggle is in various states.
 * @property {Object<string, number>}          _durations                   - The duration times (in milliseconds) for various aspects throughout the tab toggle.
 * @property {Object<string, number>}          _delays                      - The delay times (in milliseconds) for various aspects throughout the tab toggle.
 * @property {string}                          _focusState                  - The current state of the tab toggle's focus.
 * @property {string}                          _currentEvent                - The last type of event triggered within the tab toggle.
 * @property {string}                          _breakpoint                  - The breakpoint that the tab toggle will call media query list events.
 * @property {string}                          _mediaQueryString            - The media query to use to trigger media query list events.
 * @property {MediaQueryList|null}             _mediaQueryList              - The MediaQueryList for the tab toggle.
 * @property {Function}                        _mediaQueryListEventCallback - The callback for media query list events.
 * @property {Object<string, number>}          _intervals                   - Intervals throughout the tab toggle.
 * @property {Object<string, number>}          _timeouts                    - Timeouts throughout the tab toggle.
 * @property {object[]}                        _listeners                   - Event listeners throughout the tab toggle.
 * @property {string}                          _prefix                      - The prefix used for CSS custom properties and attributes.
 * @property {string}                          _key                         - The key used to generate IDs throughout the tab toggle.
 * @property {string}                          _storageKey                  - The key used for storage.
 * @property {boolean}                         _shouldStore                 - A flag to check if the component should be stored in the StorageManager.
 * @property {string}                          _id                          - The main ID of the tab toggle.
 * @property {boolean}                         _valid                       - The validity state of the tab toggle.
 * @property {boolean}                         _initialized                 - The initialized state of the tab toggle.
 * @property {Error[]}                         _errors                      - The errors found throughout the tab toggle.
 */
class TabToggle extends CollapsibleComponent {
  _scope = "Graupl";
  _rootDOMElement = "toggle";
  _storageKey = "tabToggles";
  _name = "TabToggle";
  _shouldStore = false;

  /**
   * Constructs a new TabToggle.
   *
   * @param {object}      [options = {}]         - The options for generating the tab toggle.
   * @param {HTMLElement} options.toggleElement  - The tab toggle DOM element.
   * @param {HTMLElement} options.contentElement - The tab content DOM element.
   * @param {Tabs}        options.parentTab      - The Tabs element the toggle belongs to.
   */
  constructor({ toggleElement, contentElement, parentTab } = {}) {
    super({
      controllerElement: toggleElement,
      controlledElement: contentElement,
      expandClass: parentTab.classes.expand,
      collapseClass: parentTab.classes.collapse,
      transitionClass: parentTab.classes.transition,
      transitionDuration: parentTab.durations.transition,
      expandDuration: parentTab.durations.expand,
      collapseDuration: parentTab.durations.collapse,
      bootstrap: false,
      initialize: false,
      prefix: parentTab.prefix,
      key: parentTab.key,
    });

    // Set the protected elements.
    this._protectedDOMElements.push("content");

    // Set DOM elements.
    this._dom.toggle = toggleElement;
    this._dom.content = contentElement;

    // Set the parent tab instance.
    this._elements.parent = parentTab;

    // Register custom events.
    this._bootstrap();
  }

  /**
   * Registers the tab toggle's internal initialization and ARIA listeners.
   *
   * @protected
   */
  _registerEvents() {
    super._registerEvents();

    // Automatically expand or collapse the tab toggle based on its aria-selected attribute.
    this._addInternalEventListener(this.getEventName("preinitialize"), () => {
      this._expanded.value =
        this.dom.toggle.getAttribute("aria-selected") === "true";
      this._expanded.commit();
    });

    this._addInternalEventListener(this.getEventName("preexpand"), () => {
      // Set aria-selected to true when expanding the tab toggle.
      this.dom.toggle.setAttribute("aria-selected", "true");

      // Set the tabindex to 0 so it can be focused.
      this.dom.toggle.setAttribute("tabindex", "0");
    });
    this._addInternalEventListener(this.getEventName("precollapse"), () => {
      // Set aria-selected to false when collapsing the tab toggle.
      this.dom.toggle.setAttribute("aria-selected", "false");

      // Set the tabindex to -1.
      this.dom.toggle.setAttribute("tabindex", "-1");
    });
  }

  /**
   * The deprecated alias for isExpanded.
   *
   * @deprecated Use isExpanded instead. This property will be removed.
   *
   * @readonly
   *
   * @type {boolean}
   */
  get isActive() {
    console.warn(
      "Graupl TabToggle.isActive is deprecated and will be removed. Use isExpanded instead."
    );

    return this.isExpanded;
  }

  /**
   * The last event triggered in the parent tabs element.
   *
   * Reads and updates the parent tabs element's value.
   *
   * @type {string}
   */
  get currentEvent() {
    return this.elements.parent
      ? this.elements.parent.currentEvent
      : super.currentEvent;
  }

  set currentEvent(value) {
    if (this.elements.parent) {
      this.elements.parent.currentEvent = value;
    } else {
      super.currentEvent = value;
    }
  }

  /**
   * A flag to check if the parent tabs element allows the toggle to be focused in the DOM.
   *
   * @readonly
   *
   * @type {boolean}
   */
  get shouldFocus() {
    return this.elements.parent
      ? this.elements.parent.shouldFocus
      : super.shouldFocus;
  }

  /**
   * Reads the expandClass setting from the parent tabs element.
   *
   * Setting this value also updates the parent tabs element.
   *
   * @type {string|string[]}
   */
  get expandClass() {
    return this.elements.parent.expandClass;
  }

  set expandClass(value) {
    this.elements.parent.expandClass = value;
    this._classes.expand = value;
  }

  /**
   * Reads the collapseClass setting from the parent tabs element.
   *
   * Setting this value also updates the parent tabs element.
   *
   * @type {string|string[]}
   */
  get collapseClass() {
    return this.elements.parent.collapseClass;
  }

  set collapseClass(value) {
    this.elements.parent.collapseClass = value;
    this._classes.collapse = value;
  }

  /**
   * Reads the transitionClass setting from the parent tabs element.
   *
   * Setting this value also updates the parent tabs element.
   *
   * @type {string|string[]}
   */
  get transitionClass() {
    return this.elements.parent.transitionClass;
  }

  set transitionClass(value) {
    this.elements.parent.transitionClass = value;
    this._classes.transition = value;
  }

  /**
   * Reads the transitionDuration setting from the parent tabs element.
   *
   * Setting this value also updates the parent tabs element.
   *
   * @type {number}
   */
  get transitionDuration() {
    return this.elements.parent.transitionDuration;
  }

  set transitionDuration(value) {
    this.elements.parent.transitionDuration = value;
    this._durations.transition = value;
  }

  /**
   * Reads the expandDuration setting from the parent tabs element.
   *
   * Setting this value also updates the parent tabs element.
   *
   * @type {number}
   */
  get expandDuration() {
    return this.elements.parent.expandDuration;
  }

  set expandDuration(value) {
    this.elements.parent.expandDuration = value;
    this._durations.expand = value;
  }

  /**
   * Reads the collapseDuration setting from the parent tabs element.
   *
   * Setting this value also updates the parent tabs element.
   *
   * @type {number}
   */
  get collapseDuration() {
    return this.elements.parent.collapseDuration;
  }

  set collapseDuration(value) {
    this.elements.parent.collapseDuration = value;
    this._durations.collapse = value;
  }

  /**
   * Sets the IDs of the tab toggle and its content if they do not already exist.
   *
   * The generated IDs use the following format:
   *   - toggle: `tab-toggle-${key}-${index}`
   *   - content: `tab-content-${key}-${index}`
   *
   * Where `${key}` is the parent's key and `${index}` is the toggles index in the list of the parent's toggles.
   *
   * @protected
   */
  _setIds() {
    // Get the required information for IDs.
    const { key } = this.elements.parent;
    const index = this.elements.parent.dom.tabToggles.indexOf(this.dom.toggle);

    this.dom.toggle.id = this.dom.toggle.id || `tab-toggle-${key}-${index}`;
    this.dom.content.id = this.dom.content.id || `tab-content-${key}-${index}`;

    this._id = this.dom.toggle.id;
  }

  /**
   * Sets the ARIA attributes on the tab toggle and its content.
   */
  _setAriaAttributes() {
    // Set the ARIA attributes for the tab item toggle.
    this.dom.toggle.setAttribute("role", "tab");

    // If aria-selected is not explicitly set to "true", then set it to "false".
    if (this.dom.toggle.getAttribute("aria-selected") !== "true") {
      this.dom.toggle.setAttribute("aria-selected", "false");
    }

    // Set the aria-controls attribute for the toggle.
    this.dom.toggle.setAttribute("aria-controls", this.dom.content.id);

    // Set the role for the content.
    this.dom.content.setAttribute("role", "tabpanel");

    // Set the aria-labelledby attribute for the content.
    this.dom.content.setAttribute("aria-labelledby", this.dom.toggle.id);
  }

  /**
   * Checks whether a locked selected sibling permits changing the selection.
   *
   * @protected
   *
   * @param {Object<boolean>} [options = {}]                        - Options for selecting the tab.
   * @param {boolean}         [options.force = !this.isInitialized] - Whether to force selection despite a locked sibling.
   * @return {boolean} - Whether selection is allowed by the sibling locking rules.
   */
  _canSelect({ force = !this.isInitialized } = {}) {
    return (
      force ||
      !this.elements.parent.elements.tabToggles.some(
        (toggle) => toggle !== this && toggle.isExpanded && toggle.isLocked
      )
    );
  }

  /**
   * Expands the tab toggle's content.
   *
   * Keeps a locked sibling selected unless the new selection is forced.
   * Core handles the expansion state, classes, transitions, and events.
   *
   * @param {Object<boolean>} [options = {}]                        - Options passed to Core's expand method.
   * @param {boolean}         [options.force = !this.isInitialized] - Whether to force the selection change.
   */
  expand(options = {}) {
    if (!this._canSelect(options)) return;

    super.expand(options);
  }

  /**
   * Previews the tab toggle's content without entering it.
   *
   * Applies the same sibling locking rules as expand.
   *
   * @param {Object<boolean>} [options = {}]                        - Options passed to Core's preview method.
   * @param {boolean}         [options.force = !this.isInitialized] - Whether to force the selection change.
   */
  preview(options = {}) {
    if (!this._canSelect(options)) return;

    super.preview(options);
  }

  /**
   * Collapses all sibling toggles within the same Tabs element.
   *
   * @param {Object<boolean>} [options = {}] - Options passed to each sibling's collapse method.
   */
  collapseSiblings(options = {}) {
    if (this.elements.parent) {
      this.elements.parent.elements.tabToggles.forEach((toggle) => {
        if (toggle !== this && toggle.isExpanded) {
          toggle.collapse(options);
        }
      });
    }
  }

  /**
   * Calls expand using the former method name.
   *
   * @deprecated Use expand instead. This method will be removed.
   *
   * @param {...*} args - Arguments forwarded to expand.
   * @return {*} - The result of calling expand.
   */
  show(...args) {
    console.warn(
      "Graupl TabToggle.show() is deprecated and will be removed. Use expand() instead."
    );

    return this.expand(...args);
  }

  /**
   * Calls collapse using the former method name.
   *
   * @deprecated Use collapse instead. This method will be removed.
   *
   * @param {...*} args - Arguments forwarded to collapse.
   * @return {*} - The result of calling collapse.
   */
  hide(...args) {
    console.warn(
      "Graupl TabToggle.hide() is deprecated and will be removed. Use collapse() instead."
    );

    return this.collapse(...args);
  }

  /**
   * Calls collapseSiblings using the former method name.
   *
   * @deprecated Use collapseSiblings instead. This method will be removed.
   *
   * @param {...*} args - Arguments forwarded to collapseSiblings.
   * @return {*} - The result of calling collapseSiblings.
   */
  hideSiblings(...args) {
    console.warn(
      "Graupl TabToggle.hideSiblings() is deprecated and will be removed. Use collapseSiblings() instead."
    );

    return this.collapseSiblings(...args);
  }
}

export default TabToggle;
