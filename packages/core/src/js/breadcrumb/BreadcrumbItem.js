/**
 * @file
 * BreadrumbItem class.
 */

/* global Breadcrumb */

import Component from "@accessible-ecosystem/core/Component.js";

/**
 * The Breadcrumb Item component.
 *
 * @extends Component
 *
 * Protected fields are documented below.
 *
 * @property {Object<string, HTMLElement|null>} _dom                         - The DOM elements within the breadcrumb.
 * @property {HTMLElement}                      _dom.item                    - The breadcrumb item element.
 * @property {?HTMLElement}                     _dom.link                    - The breadcrumb link element.
 * @property {string}                           _rootDOMElement              - The root DOM element of the breadcrumb item.
 * @property {string[]}                         _protectedDOMElements        - The DOM elements within the breadcrumb item that cannot be reset or generated by the breadcrumb item itself.
 * @property {Object<string, string>}           _selectors                   - The query selectors used by the breadcrumb item.
 * @property {Object<string, Breadcrumb>}       _elements                    - The instantiated elements within the breadcrumb item.
 * @property {Breadcrumb}                       _elements.parent             - The parent breadcrumb instance of the breadcrumb item.
 * @property {Object<string, string|string[]>}  _classes                     - The CSS classes to apply when the breadcrumb item is in various states.
 * @property {string|string[]}                  _classes.initialize          - The class(es) to apply when the breadcrumb item is initializing.
 * @property {Object<string, number>}           _durations                   - The duration times (in milliseconds) for various aspects throughout the breadcrumb item.
 * @property {Function}                         _mediaQueryListEventCallback - The callback for media query list events.
 * @property {string}                           _storageKey                  - The key used for storage.
 * @property {boolean}                          _shouldStore                 - A flag to check if the component should be stored in the StorageManager.
 * @property {Object<string, CustomEvent>}      _events                      - Custom events that can be triggered throughout the breadcrumb item.
 * @property {Object<string, number>}           _delays                      - The delay times (in milliseconds) for various aspects througho1t the breadcrumb item.
 * @property {string}                           _focusState                  - The current state of the breadcrumb item's focus.
 * @property {string}                           _currentEvent                - The last type of event triggered within the breadcrumb item.
 * @property {string}                           _breakpoint                  - The breakpoint that the breadcrumb item will call media query list events.
 * @property {string}                           _mediaQueryString            - The media query to use to trigger media query list events.
 * @property {MediaQueryList|null}              _mediaQueryList              - The MediaQueryList for the breadcrumb item.
 * @property {Object<string, number>}           _intervals                   - Intervals throughout the breadcrumb item.
 * @property {Object<string, number>}           _timeouts                    - Timeouts throughout the breadcrumb item.
 * @property {object[]}                         _listeners                   - Event listeners throughout the breadcrumb item.
 * @property {string}                           _prefix                      - The prefix used for CSS custom properties and attributes.
 * @property {string}                           _key                         - The key used to generate IDs throughout the breadcrumb item.
 * @property {string}                           _id                          - The main ID of the breadcrumb item.
 * @property {boolean}                          _valid                       - The validity state of the breadcrumb item.
 * @property {boolean}                          _initialized                 - The initialized state of the breadcrumb item.
 * @property {Error[]}                          _errors                      - The errors found throughout the breadcrumb item.
 * @property {boolean}                          _toggle                      - A flag marking whether the breadcrumb item is a toggle item.
 */
class BreadcrumbItem extends Component {
  _scope = "Graupl";
  _rootDOMElement = "item";
  _name = "BreadcrumbItem";
  _storageKey = "breadcrumbItems";
  _shouldStore = false;
  _toggle = false;

  constructor({
    breadcrumbItemElement,
    breadcrumbLinkElement = null,
    parentBreadcrumb,
    isToggle = false,
    prefix = "graupl-",
    key = null,
    initializeClass = "initializing",
  }) {
    super({
      bootstrap: false,
      initialize: false,
      prefix,
      key,
      initializeClass,
    });

    // Set the protected elements.
    this._protectedDOMElements.push("link");

    // Set the DOM elements.
    this._dom.item = breadcrumbItemElement;
    this._dom.link = breadcrumbLinkElement;

    // Set the instantiated elements.
    this._elements.parent = parentBreadcrumb;

    // Set the toggle state.
    this._toggle = isToggle;
    this._bootstrap();
  }

  /**
   * The last event triggered in the parent breadcrumb.
   *
   * Reads and updates the parent breadcrumb's value.
   *
   * @type {string}
   */
  get currentEvent() {
    return this.elements.parent
      ? this.elements.parent.currentEvent
      : super.currentEvent;
  }

  set currentEvent(value) {
    if (this.elements.parent) {
      this.elements.parent.currentEvent = value;
    } else {
      super.currentEvent = value;
    }
  }

  /**
   * A flag to check if the parent breadcrumb allows the item to be focused in the DOM.
   *
   * @readonly
   *
   * @type {boolean}
   */
  get shouldFocus() {
    return this.elements.parent
      ? this.elements.parent.shouldFocus
      : super.shouldFocus;
  }

  /**
   * A flag marking whether the breadcrumb item is a toggle item.
   *
   * @readonly
   *
   * @type {boolean}
   *
   * @see _toggle
   */
  get isToggle() {
    return this._toggle;
  }

  /**
   * Focuses the breadcrumb item's link if the parent breadcrumb's shouldFocus value is `true`.
   */
  focus() {
    this.focusState = "self";

    this._cancelAnimationFrame("blur");
    if (this.shouldFocus && this.dom.link) {
      this._requestAnimationFrame(() => {
        this.dom.link.focus();
      }, "focus");
    }
  }

  /**
   * Blurs the breadcrumb item's link if the parent breadcrumb's shouldFocus value is `true`.
   */
  blur() {
    this.focusState = "none";

    this._cancelAnimationFrame("focus");
    if (this.shouldFocus && this.dom.link) {
      this._requestAnimationFrame(() => {
        this.dom.link.blur();
      }, "blur");
    }
  }
}

export default BreadcrumbItem;
