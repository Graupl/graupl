/* global Accordion, TransactionalValue */

import { isTag } from "@accessible-ecosystem/core/validate.js";
import CollapsibleComponent from "@accessible-ecosystem/core/CollapsibleComponent.js";

/**
 * @event grauplAccordionItemExpand
 * Fired when the accordion item is expanded.
 *
 * @type {CustomEvent}
 *
 * @property {boolean}                       bubbles          - Whether the event bubbles.
 * @property {Object<string, AccordionItem>} detail           - The event details.
 * @property {AccordionItem}                 detail.component - The accordion item that was expanded.
 */

/**
 * @event grauplAccordionItemCollapse
 * Fired when the accordion item is collapsed.
 *
 * @type {CustomEvent}
 *
 * @property {boolean}                       bubbles          - Whether the event bubbles.
 * @property {Object<string, AccordionItem>} detail           - The event details.
 * @property {AccordionItem}                 detail.component - The accordion item that was collapsed.
 */

/**
 * The Accordion item component.
 *
 * @extends CollapsibleComponent
 *
 * Protected fields are documented below.
 *
 * @property {Object<string, HTMLElement>}     _dom                         - The DOM elements within the accordion item.
 * @property {HTMLElement}                     _dom.item                    - The accordion item element.
 * @property {HTMLElement}                     _dom.toggle                  - The controller element.
 * @property {HTMLElement}                     _dom.header                  - The header element.
 * @property {HTMLElement}                     _dom.content                 - The content element.
 * @property {string}                          _rootDOMElement              - The root DOM element of the accordion item.
 * @property {string[]}                        _protectedDOMElements        - The DOM elements within the accordion item that cannot be reset or generated by the accordion item itself.
 * @property {Object<string, Accordion>}       _elements                    - The instantiated elements within the accordion item.
 * @property {Accordion}                       _elements.parent             - The parent accordion containing this item.
 * @property {TransactionalValue<boolean>}     _expanded                    - The expanded state of the accordion item.
 * @property {TransactionalValue<boolean>}     _locked                      - The locked state of the accordion item.
 * @property {Object<string, CustomEvent>}     _events                      - Custom events that can be triggered throughout the accordion item.
 * @property {grauplAccordionItemExpand}       _events.expand               - The event triggered when the accordion item is expanded.
 * @property {grauplAccordionItemCollapse}     _events.collapse             - The event triggered when the accordion item is collapsed.
 * @property {Object<string, string>}          _selectors                   - The query selectors used by the accordion item.
 * @property {Object<string, string|string[]>} _classes                     - The CSS classes to apply when the accordion item is in various states.
 * @property {Object<string, number>}          _durations                   - The duration times (in milliseconds) for various aspects throughout the accordion item.
 * @property {Object<string, number>}          _delays                      - The delay times (in milliseconds) for various aspects throughout the accordion item.
 * @property {string}                          _focusState                  - The current state of the accordion item's focus.
 * @property {string}                          _currentEvent                - The last type of event triggered within the accordion item.
 * @property {string}                          _breakpoint                  - The breakpoint that the accordion item will call media query list events.
 * @property {string}                          _mediaQueryString            - The media query to use to trigger media query list events.
 * @property {MediaQueryList|null}             _mediaQueryList              - The MediaQueryList for the accordion item.
 * @property {Function}                        _mediaQueryListEventCallback - The callback for media query list events.
 * @property {Object<string, number>}          _intervals                   - Intervals throughout the accordion item.
 * @property {Object<string, number>}          _timeouts                    - Timeouts throughout the accordion item.
 * @property {object[]}                        _listeners                   - Event listeners throughout the accordion item.
 * @property {string}                          _prefix                      - The prefix used for CSS custom properties and attributes.
 * @property {string}                          _key                         - The key used to generate IDs throughout the accordion item.
 * @property {string}                          _name                        - The component name of the accordion item.
 * @property {string}                          _storageKey                  - The key used for storage.
 * @property {boolean}                         _shouldStore                 - A flag to check if the component should be stored in the StorageManager.
 * @property {string}                          _id                          - The main ID of the accordion item.
 * @property {boolean}                         _valid                       - The validity state of the accordion item.
 * @property {boolean}                         _initialized                 - The initialized state of the accordion item.
 * @property {Error[]}                         _errors                      - The errors found throughout the accordion item.
 */
class AccordionItem extends CollapsibleComponent {
  _scope = "Graupl";
  _rootDOMElement = "item";
  _name = "AccordionItem";
  _storageKey = "accordionItems";
  _shouldStore = false;

  /**
   * Constructs a new AccordionItem.
   *
   * @param {object}      options                             - The options object.
   * @param {HTMLElement} options.accordionItemElement        - The accordion item element.
   * @param {HTMLElement} options.accordionItemToggleElement  - The toggle element.
   * @param {HTMLElement} options.accordionItemHeaderElement  - The header element.
   * @param {HTMLElement} options.accordionItemContentElement - The content element.
   * @param {Accordion}   options.parentAccordion             - The accordion containing this item.
   */
  constructor({
    accordionItemElement,
    accordionItemToggleElement,
    accordionItemHeaderElement,
    accordionItemContentElement,
    parentAccordion = null,
  }) {
    super({
      controllerElement: accordionItemToggleElement,
      controlledElement: accordionItemElement,
      expandClass: parentAccordion.classes.expand,
      collapseClass: parentAccordion.classes.collapse,
      transitionClass: parentAccordion.classes.transition,
      transitionDuration: parentAccordion.durations.transition,
      expandDuration: parentAccordion.durations.expand,
      collapseDuration: parentAccordion.durations.collapse,
      lockClass: "",
      unlockClass: "",
      bootstrap: false,
      initialize: false,
      prefix: parentAccordion.prefix,
      key: parentAccordion.key,
    });

    // Set the protected elements.
    this._protectedDOMElements.push("toggle", "header", "content");

    // Set DOM elements.
    this._dom.item = accordionItemElement;
    this._dom.toggle = accordionItemToggleElement;
    this._dom.header = accordionItemHeaderElement;
    this._dom.content = accordionItemContentElement;

    // Set the accordion elements.
    this._elements.parent = parentAccordion;

    // Accordion initialization also enforces the parent's expansion rules.
    this._bootstrap();
  }

  /**
   * Registers the accordion item's internal initialization, ARIA, and height listeners.
   *
   * @protected
   */
  _registerEvents() {
    super._registerEvents();

    this._addInternalEventListener(this.getEventName("preinitialize"), () => {
      this._expanded.value =
        this.dom.toggle.getAttribute("aria-expanded") === "true";
      this._expanded.commit();
    });

    this._addInternalEventListener(this.getEventName("preexpand"), () => {
      this._cancelAnimationFrame("accordionHeight");
      this.dom.toggle.setAttribute("aria-expanded", "true");
      this.dom.content.removeAttribute("inert");

      // Start at the header height before Core applies the expanded class.
      this.dom.item.style.height = `${this.dom.header.getBoundingClientRect().height}px`;
    });
    this._addInternalEventListener(this.getEventName("expand"), () => {
      this.dom.item.style.height = `${this.dom.header.getBoundingClientRect().height + this.dom.content.getBoundingClientRect().height}px`;
    });
    this._addInternalEventListener(this.getEventName("postexpand"), () => {
      this.dom.item.style.height = "";
    });

    this._addInternalEventListener(this.getEventName("precollapse"), () => {
      this._cancelAnimationFrame("accordionHeight");
      this.dom.toggle.setAttribute("aria-expanded", "false");
      this.dom.content.setAttribute("inert", "true");
      this.dom.item.style.height = `${this.dom.item.getBoundingClientRect().height}px`;

      // Collapse to the header height as Core removes the expanded class.
      this._requestAnimationFrame(() => {
        this.dom.item.style.height = `${this.dom.header.getBoundingClientRect().height}px`;
      }, "accordionHeight");
    });
    this._addInternalEventListener(this.getEventName("postcollapse"), () => {
      this._cancelAnimationFrame("accordionHeight");
      this.dom.item.style.height = "";
    });
  }

  /**
   * The deprecated alias for isExpanded.
   *
   * @deprecated Use isExpanded instead. This property will be removed.
   *
   * @readonly
   *
   * @type {boolean}
   */
  get isOpen() {
    console.warn(
      "Graupl AccordionItem.isOpen is deprecated and will be removed. Use isExpanded instead."
    );

    return this.isExpanded;
  }

  /**
   * The last event triggered in the parent accordion.
   *
   * Reads and updates the parent accordion's value.
   *
   * @type {string}
   */
  get currentEvent() {
    return this.elements.parent
      ? this.elements.parent.currentEvent
      : super.currentEvent;
  }

  set currentEvent(value) {
    if (this.elements.parent) {
      this.elements.parent.currentEvent = value;
    } else {
      super.currentEvent = value;
    }
  }

  /**
   * A flag to check if the parent accordion allows the item to be focused in the DOM.
   *
   * @readonly
   *
   * @type {boolean}
   */
  get shouldFocus() {
    return this.elements.parent
      ? this.elements.parent.shouldFocus
      : super.shouldFocus;
  }

  /**
   * Reads the expandClass setting from the parent accordion.
   *
   * Setting this value also updates the parent accordion.
   *
   * @type {string|string[]}
   */
  get expandClass() {
    return this.elements.parent.expandClass;
  }

  set expandClass(value) {
    this.elements.parent.expandClass = value;
    this._classes.expand = value;
  }

  /**
   * Reads the collapseClass setting from the parent accordion.
   *
   * Setting this value also updates the parent accordion.
   *
   * @type {string|string[]}
   */
  get collapseClass() {
    return this.elements.parent.collapseClass;
  }

  set collapseClass(value) {
    this.elements.parent.collapseClass = value;
    this._classes.collapse = value;
  }

  /**
   * Reads the transitionClass setting from the parent accordion.
   *
   * Setting this value also updates the parent accordion.
   *
   * @type {string|string[]}
   */
  get transitionClass() {
    return this.elements.parent.transitionClass;
  }

  set transitionClass(value) {
    this.elements.parent.transitionClass = value;
    this._classes.transition = value;
  }

  /**
   * Reads the transitionDuration setting from the parent accordion.
   *
   * Setting this value also updates the parent accordion.
   *
   * @type {number}
   */
  get transitionDuration() {
    return this.elements.parent.transitionDuration;
  }

  set transitionDuration(value) {
    this.elements.parent.transitionDuration = value;
    this._durations.transition = value;
  }

  /**
   * Reads the expandDuration setting from the parent accordion.
   *
   * Setting this value also updates the parent accordion.
   *
   * @type {number}
   */
  get expandDuration() {
    return this.elements.parent.expandDuration;
  }

  set expandDuration(value) {
    this.elements.parent.expandDuration = value;
    this._durations.expand = value;
  }

  /**
   * Reads the collapseDuration setting from the parent accordion.
   *
   * Setting this value also updates the parent accordion.
   *
   * @type {number}
   */
  get collapseDuration() {
    return this.elements.parent.collapseDuration;
  }

  set collapseDuration(value) {
    this.elements.parent.collapseDuration = value;
    this._durations.collapse = value;
  }

  /**
   * Sets the IDs for the accordion item and its elements if they don't exist.
   *
   * The generated IDs use the parent accordion's key and follows the pattern:
   *  - Accordion item: `accordion-item-{key}-{index}`
   *  - Accordion item toggle: `accordion-item-toggle-{key}-{index}`
   *  - Accordion item content: `accordion-item-content-{key}-{index}`
   */
  _setIds() {
    // Get the required information for IDs.
    const { key } = this.elements.parent;
    const index = this.elements.parent.dom.accordionItems.indexOf(
      this.dom.item
    );

    this.dom.item.id = this.dom.item.id || `accordion-item-${key}-${index}`;
    this.dom.toggle.id =
      this.dom.toggle.id || `accordion-item-toggle-${key}-${index}`;
    this.dom.header.id =
      this.dom.header.id || `accordion-item-header-${key}-${index}`;
    this.dom.content.id =
      this.dom.content.id || `accordion-item-content-${key}-${index}`;
  }

  /**
   * Sets the ARIA attributes for the accordion item and its elements.
   */
  _setAriaAttributes() {
    // Set the ARIA attributes for the accordion item toggle.
    // If the toggle is not a button, then set the role to "button".
    if (
      !isTag("button", { toggle: this.dom.toggle }, { shouldThrow: false })
        .status
    ) {
      this.dom.toggle.setAttribute("role", "button");
    }

    // If aria-expanded is not explicitly set to "true", then set it to "false".
    if (this.dom.toggle.getAttribute("aria-expanded") !== "true") {
      this.dom.toggle.setAttribute("aria-expanded", "false");
    }

    // Set the aria-controls attribute for the toggle.
    this.dom.toggle.setAttribute("aria-controls", this.dom.content.id);

    // Set the ARIA attributes for the accordion item content.
    // If the content is not a section, then set the role to "region".
    if (
      !isTag("section", { content: this.dom.content }, { shouldThrow: false })
        .status
    ) {
      this.dom.content.setAttribute("role", "region");
    }

    // Set the aria-labelledby attribute for the content.
    this.dom.content.setAttribute("aria-labelledby", this.dom.toggle.id);
  }

  /**
   * Collapses the accordion item.
   *
   * Keeps the last expanded item open when the parent requires one.
   * Core handles the collapse state, classes, transitions, and events.
   *
   * @param {Object<boolean>} [options = {}]                                         - Options passed to Core's collapse method.
   * @param {boolean}         [options.force = !this.isInitialized]                  - Whether to force the collapse action.
   * @param {boolean}         [options.preserveState = false]                        - Whether to preserve the expanded state.
   * @param {boolean}         [options.emit = this.isInitialized && this.shouldEmit] - Emit the collapse event once collapsed.
   * @param {boolean}         [options.transition = this.isInitialized]              - Respect the transition class.
   */
  collapse(options = {}) {
    if (
      this.isInitialized &&
      !options.force &&
      this.isExpanded &&
      !this.elements.parent.allowCollapseAll &&
      this.elements.parent.expandedAccordionItems.length <= 1
    ) {
      return;
    }

    super.collapse(options);
  }

  /**
   * Focuses the accordion item.
   *
   * Sets the focus state to "self" and focuses the toggle if shouldFocus is true.
   */
  focus() {
    this.focusState = "self";

    if (this.shouldFocus) {
      this.dom.toggle.focus();
    }

    if (this.expandOnFocus) this.expand();
  }

  /**
   * Blurs the accordion item.
   *
   * Sets the focus state to "none" and blurs the toggle if shouldFocus is true.
   */
  blur() {
    this.focusState = "none";

    if (this.shouldFocus) {
      this.dom.toggle.blur();
    }

    if (this.collapseOnBlur) this.collapse();
  }

  /**
   * Closes the siblings of the accordion item.
   */
  collapseSiblings() {
    if (this.elements.parent) {
      this.elements.parent.elements.accordionItems.forEach((item) => {
        if (item !== this) {
          item.collapse();
        }
      });
    }
  }

  /**
   * Unlocks the siblings of the accordion item.
   *
   * @param {Object<boolean>} [options = {}] - Options passed to each sibling's unlock method.
   */
  unlockSiblings(options = {}) {
    if (this.elements.parent) {
      this.elements.parent.elements.accordionItems.forEach((item) => {
        if (item !== this) {
          item.unlock(options);
        }
      });
    }
  }

  /**
   * Calls expand using the former method name.
   *
   * @deprecated Use expand instead. This method will be removed.
   *
   * @param {...*} args - Arguments forwarded to expand.
   * @return {*} - The result of calling expand.
   */
  show(...args) {
    console.warn(
      "Graupl AccordionItem.show() is deprecated and will be removed. Use expand() instead."
    );

    return this.expand(...args);
  }

  /**
   * Calls collapse using the former method name.
   *
   * @deprecated Use collapse instead. This method will be removed.
   *
   * @param {...*} args - Arguments forwarded to collapse.
   * @return {*} - The result of calling collapse.
   */
  hide(...args) {
    console.warn(
      "Graupl AccordionItem.hide() is deprecated and will be removed. Use collapse() instead."
    );

    return this.collapse(...args);
  }

  /**
   * Calls collapseSiblings using the former method name.
   *
   * @deprecated Use collapseSiblings instead. This method will be removed.
   *
   * @param {...*} args - Arguments forwarded to collapseSiblings.
   * @return {*} - The result of calling collapseSiblings.
   */
  closeSiblings(...args) {
    console.warn(
      "Graupl AccordionItem.closeSiblings() is deprecated and will be removed. Use collapseSiblings() instead."
    );

    return this.collapseSiblings(...args);
  }
}

export default AccordionItem;
