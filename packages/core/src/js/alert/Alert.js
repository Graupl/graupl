/**
 * @file
 * The Alert class.
 */

import {
  keyPress,
  preventEvent,
} from "@accessible-ecosystem/core/eventHelpers.js";
import CollapsibleComponent from "@accessible-ecosystem/core/CollapsibleComponent.js";

/**
 * @event grauplAlertExpand
 * Fired when the alert is expanded.
 *
 * @type {CustomEvent}
 *
 * @property {boolean}               bubbles      - Whether the event bubbles.
 * @property {Object<string, Alert>} detail       - The detail object.
 * @property {Alert}                 detail.alert - The alert that was expanded.
 */

/**
 * @event grauplAlertCollapse
 * Fired when the alert is collapsed.
 *
 * @type {CustomEvent}
 *
 * @property {boolean}               bubbles      - Whether the event bubbles.
 * @property {Object<string, Alert>} detail       - The detail object.
 * @property {Alert}                 detail.alert - The alert that was collapsed.
 */

/**
 * The Alert component.
 *
 * @extends CollapsibleComponent
 *
 * Protected fields are documented below.
 *
 * @property {Object<string, HTMLElement|null>} _dom                         - The DOM elements within the alert.
 * @property {HTMLElement}                      _dom.alert                   - The alert element.
 * @property {?HTMLElement}                     _dom.controller              - The alert controller element.
 * @property {string}                           _rootDOMElement              - The root DOM element of the alert.
 * @property {string[]}                         _protectedDOMElements        - The DOM elements within the alert that cannot be reset or generated by the alert itself.
 * @property {Object<string, string|string[]>}  _classes                     - The CSS classes to apply when the alert is in various states.
 * @property {string|string[]}                  _classes.expand              - The class(es) to apply when the alert is expanded.
 * @property {string|string[]}                  _classes.collapse            - The class(es) to apply when the alert is collapsed.
 * @property {string|string[]}                  _classes.transition          - The class(es) to apply when the alert is transitioning between states.
 * @property {string|string[]}                  _classes.initialize          - The class(es) to apply when the alert is initializing.
 * @property {Object<string, number>}           _durations                   - The duration times (in milliseconds) for various aspects throughout the alert.
 * @property {number}                           _durations.transition        - The duration time (in milliseconds) for the transition between expanded and collapsed states.
 * @property {number}                           _durations.expand            - The duration time (in milliseconds) for the transition from collapsed to expanded states.
 * @property {number}                           _durations.collapse          - The duration time (in milliseconds) for the transition from expanded to collapsed states.
 * @property {Object<string, CustomEvent>}      _events                      - Custom events that can be triggered throughout the alert.
 * @property {grauplAlertExpand}                _events.expand               - The event triggered when the alert is expanded.
 * @property {grauplAlertCollapse}              _events.collapse             - The event triggered when the alert is collapsed.
 * @property {string}                           _storageKey                  - The key used for storage.
 * @property {boolean}                          _shouldStore                 - A flag to check if the component should be stored in the StorageManager.
 * @property {Object<string, string>}           _selectors                   - The query selectors used by the alert.
 * @property {Object<string, object>}           _elements                    - The instantiated elements within the alert.
 * @property {Object<string, number>}           _delays                      - The delay times (in milliseconds) for various aspects throughout the alert.
 * @property {string}                           _focusState                  - The current state of the alert's focus.
 * @property {string}                           _currentEvent                - The last type of event triggered within the alert.
 * @property {string}                           _breakpoint                  - The breakpoint that the alert will call media query list events.
 * @property {string}                           _mediaQueryString            - The media query to use to trigger media query list events.
 * @property {MediaQueryList|null}              _mediaQueryList              - The MediaQueryList for the alert.
 * @property {Function}                         _mediaQueryListEventCallback - The callback for media query list events.
 * @property {Object<string, number>}           _intervals                   - Intervals throughout the alert.
 * @property {Object<string, number>}           _timeouts                    - Timeouts throughout the alert.
 * @property {object[]}                         _listeners                   - Event listeners throughout the alert.
 * @property {string}                           _prefix                      - The prefix used for CSS custom properties and attributes.
 * @property {string}                           _key                         - The key used to generate IDs throughout the alert.
 * @property {string}                           _name                        - The component name of the alert.
 * @property {string}                           _id                          - The main ID of the alert.
 * @property {boolean}                          _valid                       - The validity state of the alert.
 * @property {boolean}                          _initialized                 - The initialized state of the alert.
 * @property {Error[]}                          _errors                      - The errors found throughout the alert.
 */
class Alert extends CollapsibleComponent {
  _scope = "Graupl";
  _rootDOMElement = "alert";
  _storageKey = "alerts";
  _name = "Alert";

  /**
   * Constructs a new `Alert`.
   *
   * @param {object}               [options = {}]                            - The options object.
   * @param {HTMLElement}          options.alertElement                      - The alert element.
   * @param {?HTMLElement}         [options.controllerElement = null]        - The controller element.
   * @param {string|string[]|null} [options.expandClass = show]              - The class(es) to apply when the alert is expanded.
   * @param {string|string[]|null} [options.collapseClass = hide]            - The class(es) to apply when the alert is collapsed.
   * @param {string|string[]|null} [options.transitionClass = transitioning] - The class(es) to apply when the alert is transitioning between states.
   * @param {number}               [options.transitionDuration = 150]        - The duration of the transition between "expanded" and "collapsed" states (in milliseconds).
   * @param {number}               [options.expandDuration = -1]             - The duration of the transition from "collapsed" to "expanded" states (in milliseconds).
   * @param {number}               [options.collapseDuration = -1]           - The duration of the transition from "expanded" to "collapsed" states (in milliseconds).
   * @param {boolean}              [options.expanded = true]                 - A flag to determine the initial state of the alert.
   * @param {?string}              [options.prefix = graupl-]                - The prefix used for CSS custom properties and attributes.
   * @param {?string}              [options.key = null]                      - The key used to generate IDs throughout the alert.
   * @param {?(string|string[])}   [options.initializeClass = initializing]  - The class(es) to apply when the alert is initializing.
   * @param {boolean}              [options.initialize = false]              - A flag to initialize the alert immediately upon creation.
   * @param {?(string|string[])}   [options.showClass]                       - Deprecated. Use expandClass; this option takes precedence when supplied.
   * @param {?(string|string[])}   [options.hideClass]                       - Deprecated. Use collapseClass; this option takes precedence when supplied.
   * @param {number}               [options.showDuration]                    - Deprecated. Use expandDuration; this option takes precedence when supplied.
   * @param {number}               [options.hideDuration]                    - Deprecated. Use collapseDuration; this option takes precedence when supplied.
   * @param {boolean}              [options.isHidden]                        - Deprecated. Use expanded with the opposite boolean value; isHidden takes precedence when supplied.
   */
  constructor({
    alertElement,
    controllerElement = null,
    expandClass = "show",
    collapseClass = "hide",
    transitionClass = "transitioning",
    transitionDuration = 150,
    expandDuration = -1,
    collapseDuration = -1,
    expanded = true,
    prefix = "graupl-",
    key = null,
    initializeClass = "initializing",
    showClass,
    hideClass,
    showDuration,
    hideDuration,
    isHidden,
    initialize = false,
  } = {}) {
    // Map deprecated options before passing the configuration to Core.
    if (showClass !== undefined) {
      console.warn(
        'Graupl Alert option "showClass" is deprecated and will be removed. Use expandClass instead.'
      );
      expandClass = showClass;
    }

    if (hideClass !== undefined) {
      console.warn(
        'Graupl Alert option "hideClass" is deprecated and will be removed. Use collapseClass instead.'
      );
      collapseClass = hideClass;
    }

    if (showDuration !== undefined) {
      console.warn(
        'Graupl Alert option "showDuration" is deprecated and will be removed. Use expandDuration instead.'
      );
      expandDuration = showDuration;
    }

    if (hideDuration !== undefined) {
      console.warn(
        'Graupl Alert option "hideDuration" is deprecated and will be removed. Use collapseDuration instead.'
      );
      collapseDuration = hideDuration;
    }

    if (isHidden !== undefined) {
      console.warn(
        'Graupl Alert option "isHidden" is deprecated and will be removed. Use expanded instead.'
      );
      expanded = typeof isHidden === "boolean" ? !isHidden : isHidden;
    }

    super({
      controlledElement: alertElement,
      controllerElement,
      expanded,
      expandClass,
      collapseClass,
      transitionClass,
      transitionDuration,
      expandDuration,
      collapseDuration,
      prefix,
      key,
      initializeClass,
      bootstrap: false,
      initialize: false,
    });

    // Set the DOM elements.
    this._dom.alert = alertElement;

    // Register custom events.
    this._bootstrap();

    if (initialize) {
      this.initialize();
    }
  }

  /**
   * Registers alert visibility events and internal preexpand and precollapse listeners.
   *
   * @protected
   */
  _registerEvents() {
    super._registerEvents();

    this._registerEvent("preexpand", { detail: { alert: this } });
    this._registerEvent("expand", { detail: { alert: this } });
    this._registerEvent("postexpand", { detail: { alert: this } });
    this._registerEvent("precollapse", { detail: { alert: this } });
    this._registerEvent("collapse", { detail: { alert: this } });
    this._registerEvent("postcollapse", { detail: { alert: this } });

    // Keep visibility semantics on the alert, including silent actions.
    this._addInternalEventListener(this.getEventName("preexpand"), () => {
      this.dom.alert.removeAttribute("inert");
    });
    this._addInternalEventListener(this.getEventName("precollapse"), () => {
      this.dom.alert.setAttribute("inert", "true");
      this.focusState = "none";
    });
  }

  /**
   * The deprecated alias for expandClass.
   *
   * @deprecated Use expandClass instead. This property will be removed.
   *
   * @type {string|string[]}
   */
  get showClass() {
    console.warn(
      "Graupl Alert.showClass is deprecated and will be removed. Use expandClass instead."
    );

    return this.expandClass;
  }

  set showClass(value) {
    console.warn(
      "Graupl Alert.showClass is deprecated and will be removed. Use expandClass instead."
    );

    this.expandClass = value;
  }

  /**
   * The deprecated alias for collapseClass.
   *
   * @deprecated Use collapseClass instead. This property will be removed.
   *
   * @type {string|string[]}
   */
  get hideClass() {
    console.warn(
      "Graupl Alert.hideClass is deprecated and will be removed. Use collapseClass instead."
    );

    return this.collapseClass;
  }

  set hideClass(value) {
    console.warn(
      "Graupl Alert.hideClass is deprecated and will be removed. Use collapseClass instead."
    );

    this.collapseClass = value;
  }

  /**
   * The deprecated alias for expandDuration.
   *
   * @deprecated Use expandDuration instead. This property will be removed.
   *
   * @type {number}
   */
  get showDuration() {
    console.warn(
      "Graupl Alert.showDuration is deprecated and will be removed. Use expandDuration instead."
    );

    return this.expandDuration;
  }

  set showDuration(value) {
    console.warn(
      "Graupl Alert.showDuration is deprecated and will be removed. Use expandDuration instead."
    );

    this.expandDuration = value;
  }

  /**
   * The deprecated alias for collapseDuration.
   *
   * @deprecated Use collapseDuration instead. This property will be removed.
   *
   * @type {number}
   */
  get hideDuration() {
    console.warn(
      "Graupl Alert.hideDuration is deprecated and will be removed. Use collapseDuration instead."
    );

    return this.collapseDuration;
  }

  set hideDuration(value) {
    console.warn(
      "Graupl Alert.hideDuration is deprecated and will be removed. Use collapseDuration instead."
    );

    this.collapseDuration = value;
  }

  /**
   * The deprecated alias for !isExpanded.
   *
   * @deprecated Use !isExpanded instead. This property will be removed.
   *
   * @readonly
   *
   * @type {boolean}
   */
  get isHidden() {
    console.warn(
      "Graupl Alert.isHidden is deprecated and will be removed. Use !isExpanded instead."
    );

    return !this.isExpanded;
  }

  /**
   * Sets the alert and optional dismiss-button IDs if they do not already exist.
   *
   * The generated IDs use the key and follow the format:
   *  - alert: `alert-${key}`
   *  - dismiss button, when provided: `alert-controller-${key}`
   */
  _setIds() {
    this.dom.alert.id = this.dom.alert.id || `alert-${this.key}`;

    if (this.dom.controller) {
      this.dom.controller.id =
        this.dom.controller.id || `alert-controller-${this.key}`;
    }

    this._id = this.dom.alert.id;
  }

  /**
   * Sets custom props throughout the alert.
   *
   * The custom properties are:
   *   - `--graupl-alert-transition-duration`,
   *   - `--graupl-alert-show-transition-duration`, and
   *   - `--graupl-alert-hide-transition-duration`.
   *
   * The prefix of `graupl-` can be changed by setting the alert's prefix value.
   *
   * @protected
   */
  _setCustomProps() {
    this.dom.alert.style.setProperty(
      `--${this.prefix}alert-transition-duration`,
      `${this.transitionDuration}ms`
    );

    this.dom.alert.style.setProperty(
      `--${this.prefix}alert-show-transition-duration`,
      `${this.expandDuration}ms`
    );

    this.dom.alert.style.setProperty(
      `--${this.prefix}alert-hide-transition-duration`,
      `${this.collapseDuration}ms`
    );
  }

  /**
   * Handles click events on the optional dismiss button for proper use.
   *
   * - Adds a `click` listener to the controller that will collapse the alert.
   *
   * @protected
   */
  _handleClick() {
    if (this.dom.controller === null) {
      return;
    }

    this._addEventListener("click", this.dom.controller, () => this.collapse());
  }

  /**
   * Handles keydown events on the optional dismiss button for proper use.
   *
   * This method exists to assist the _handleKeyup method.
   *
   * - Adds a `keydown` listener to the controller (if it exists).
   *   - Blocks propagation on "Space" and "Enter" keys.
   */
  _handleKeydown() {
    if (this.dom.controller === null) {
      return;
    }

    this._addEventListener("keydown", this.dom.controller, (event) => {
      const key = keyPress(event);

      // Prevent default behavior for space and enter keys.
      if (key === "Space" || key === "Enter") {
        preventEvent(event);
      }
    });
  }

  /**
   * Handles keyup events on the optional dismiss button for proper use.
   *
   * - Adds a `keyup` listener to the controller (if it exists).
   *   - Collapses the alert when the user hits "Space" or "Enter".
   */
  _handleKeyup() {
    if (this.dom.controller === null) {
      return;
    }

    this._addEventListener("keyup", this.dom.controller, (event) => {
      const key = keyPress(event);

      if (key === "Space" || key === "Enter") {
        this.collapse();
      }
    });
  }

  /**
   * Calls expand using the former method name.
   *
   * @deprecated Use expand instead. This method will be removed.
   *
   * @param {...*} args - Arguments forwarded to expand.
   * @return {*} - The result of calling expand.
   */
  show(...args) {
    console.warn(
      "Graupl Alert.show() is deprecated and will be removed. Use expand() instead."
    );

    return this.expand(...args);
  }

  /**
   * Calls collapse using the former method name.
   *
   * @deprecated Use collapse instead. This method will be removed.
   *
   * @param {...*} args - Arguments forwarded to collapse.
   * @return {*} - The result of calling collapse.
   */
  hide(...args) {
    console.warn(
      "Graupl Alert.hide() is deprecated and will be removed. Use collapse() instead."
    );

    return this.collapse(...args);
  }
}

export default Alert;
