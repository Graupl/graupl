  /**
   * Registers disclosure events and internal validate, preinitialize, preexpand,
   * and precollapse listeners.
   *
   * @protected
   */
  _registerEvents() {
    super._registerEvents();

    this._registerEvent("preexpand", { detail: { disclosure: this } });
    this._registerEvent("expand", { detail: { disclosure: this } });
    this._registerEvent("postexpand", { detail: { disclosure: this } });
    this._registerEvent("precollapse", { detail: { disclosure: this } });
    this._registerEvent("collapse", { detail: { disclosure: this } });
    this._registerEvent("postcollapse", { detail: { disclosure: this } });
    this._registerEvent("prelock", { detail: { disclosure: this } });
    this._registerEvent("lock", { detail: { disclosure: this } });
    this._registerEvent("postlock", { detail: { disclosure: this } });
    this._registerEvent("preunlock", { detail: { disclosure: this } });
    this._registerEvent("unlock", { detail: { disclosure: this } });
    this._registerEvent("postunlock", { detail: { disclosure: this } });

    // Core permits a missing controller, but a disclosure requires one.
    this._addInternalEventListener(this.getEventName("validate"), () => {
      if (this.dom.controller === null) {
        const check = isValidInstance(
          HTMLElement,
          { controllerElement: this.dom.controller },
          { shouldThrow: false }
        );
        this._errors = [...this._errors, ...check.errors];
        this._valid = false;
      }
    });

    // Disclosure owns its controller attributes and initial DOM state.
    this._addInternalEventListener(this.getEventName("preinitialize"), () => {
      this._expanded.value =
        this.dom.controller.getAttribute("aria-expanded") === "true";
      this._expanded.commit();
    });
    this._addInternalEventListener(this.getEventName("preexpand"), () => {
      this.dom.controller.setAttribute("aria-expanded", "true");
      this.dom.content.removeAttribute("inert");
    });
    this._addInternalEventListener(this.getEventName("precollapse"), () => {
      this.dom.controller.setAttribute("aria-expanded", "false");
      this.dom.content.setAttribute("inert", "true");
    });
  }

